-- ============================================================================
-- Reference-data lookup: single source of truth for the small, configurable
-- enumerated dropdowns that were previously hard-coded (and inconsistent) across
-- views — payment modes, enquiry source/status, exam types, and the fixed system
-- enums (fee cycle, gender).
--
-- Design (hybrid):
--   * Entity masters (Class, Section, Department, Designation, Fee Head) keep
--     their own tables and are served from there.
--   * These small configurable/enum lists live here, ONE generic table keyed by
--     `category`, so a new list = INSERT rows (no schema/proc change).
--   * Platform DEFAULTS are seeded on tenant_id=0/school_id=0. A school may later
--     override a category by inserting its own rows; the proc then prefers those.
--   * is_system = TRUE marks lists the billing/domain logic depends on (FeeCycle,
--     Gender) — shown in dropdowns but not meant to be edited/deleted via any UI.
--
-- code  = the value stored / posted (keep identical to today's hard-coded values
--         so existing rows keep matching).
-- label = the display text.
-- ============================================================================

CREATE TABLE IF NOT EXISTS config.lookup_value (
    lookup_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      integer      NOT NULL,          -- 0 = platform default
    school_id      integer      NOT NULL,          -- 0 = platform default
    category       varchar(50)  NOT NULL,          -- 'PaymentMode', 'EnquirySource', ...
    code           varchar(80)  NOT NULL,          -- stored/posted value
    label          varchar(120) NOT NULL,          -- display text
    display_order  integer      NOT NULL DEFAULT 0,
    is_active      boolean      NOT NULL DEFAULT TRUE,
    is_system      boolean      NOT NULL DEFAULT FALSE,
    is_deleted     boolean      NOT NULL DEFAULT FALSE,
    created_at     timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uq_lookup_value UNIQUE (tenant_id, school_id, category, code)
);

CREATE INDEX IF NOT EXISTS ix_lookup_value_lookup
    ON config.lookup_value (category, tenant_id, school_id)
    WHERE is_deleted = FALSE AND is_active = TRUE;

