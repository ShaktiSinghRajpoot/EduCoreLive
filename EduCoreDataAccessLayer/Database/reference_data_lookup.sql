-- ============================================================================
-- Extend the shared dropdown provider. Entity-master branches (Class,
-- AcademicYear) are unchanged; every OTHER activity now resolves generically
-- from config.lookup_value, so new lists need no proc change.
--   p_param1 = tenantId, p_param2 = schoolId (used only by the generic branch).
-- ============================================================================
CREATE OR REPLACE PROCEDURE config.sp_dropdown_common(
    IN p_activity character varying,
    IN p_param1 character varying DEFAULT NULL::character varying,
    IN p_param2 character varying DEFAULT NULL::character varying,
    INOUT p_result refcursor DEFAULT 'result_cursor'::refcursor)
  LANGUAGE plpgsql
AS $procedure$
DECLARE
    v_tenant integer := CASE WHEN p_param1 ~ '^\d+$' THEN p_param1::int ELSE NULL END;
    v_school integer := CASE WHEN p_param2 ~ '^\d+$' THEN p_param2::int ELSE NULL END;
BEGIN
    IF p_activity = 'AcademicYear' THEN

        OPEN p_result FOR
        SELECT
            academic_year_name AS "Name",
            academic_year_id::text AS "Code",
            COALESCE(is_current, FALSE) AS "IsSelected"
        FROM academic.academic_years
        WHERE COALESCE(is_deleted, FALSE) = FALSE
          AND COALESCE(is_active, TRUE) = TRUE
          AND tenant_id = v_tenant AND school_id = v_school   -- multi-tenant scope
        ORDER BY COALESCE(is_current, FALSE) DESC, academic_year_id DESC;

    ELSIF p_activity = 'Class' THEN

        OPEN p_result FOR
        SELECT
            class_name AS "Name",
            academic_class_id::text AS "Code"
        FROM academic.academic_classes
        WHERE COALESCE(is_deleted, FALSE) = FALSE
          AND COALESCE(is_active, TRUE) = TRUE
          AND tenant_id = v_tenant AND school_id = v_school   -- multi-tenant scope
        ORDER BY academic_class_id DESC;

    ELSE
        -- Generic reference lists. Prefer the school's own rows for this
        -- category; if it has none, fall back to platform defaults (0/0).
        OPEN p_result FOR
        SELECT q."Name", q."Code"
        FROM (
            SELECT label AS "Name", code AS "Code", display_order AS ord
            FROM config.lookup_value
            WHERE category = p_activity AND is_active AND NOT is_deleted
              AND tenant_id = COALESCE(v_tenant, -1)
              AND school_id = COALESCE(v_school, -1)
            UNION ALL
            SELECT g.label, g.code, g.display_order
            FROM config.lookup_value g
            WHERE g.category = p_activity AND g.is_active AND NOT g.is_deleted
              AND g.tenant_id = 0 AND g.school_id = 0
              AND NOT EXISTS (
                  SELECT 1 FROM config.lookup_value s
                  WHERE s.category = p_activity AND s.is_active AND NOT s.is_deleted
                    AND s.tenant_id = COALESCE(v_tenant, -1)
                    AND s.school_id = COALESCE(v_school, -1))
        ) q
        ORDER BY q.ord, q."Name";

    END IF;
END;
$procedure$;
