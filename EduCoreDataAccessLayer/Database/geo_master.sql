-- ============================================================================
-- Lookup provider. Same parameter shape as config.sp_dropdown_common
-- (p_activity / p_param1 / p_param2 / p_result returning "Name","Code") so the
-- existing IBaseService.GetSelectListAsync maps it with no new plumbing.
--   Country            -> all active countries, India first
--   State   p_param1 = country_id (blank = India)
--   District p_param1 = state_id
-- ============================================================================
CREATE OR REPLACE PROCEDURE config.sp_geo_lookup(
    IN p_activity character varying,
    IN p_param1 character varying DEFAULT NULL::character varying,
    IN p_param2 character varying DEFAULT NULL::character varying,
    INOUT p_result refcursor DEFAULT 'geo_cursor'::refcursor)
 LANGUAGE plpgsql
AS $procedure$
DECLARE
    v_parent integer := CASE WHEN p_param1 ~ '^\d+$' THEN p_param1::int ELSE NULL END;
BEGIN
    IF p_activity = 'Country' THEN

        OPEN p_result FOR
        SELECT name AS "Name", country_id::text AS "Code"
        FROM config.countries
        WHERE is_active
        ORDER BY display_order, name;

    ELSIF p_activity = 'State' THEN

        -- No country passed = India (the overwhelmingly common case).
        OPEN p_result FOR
        SELECT s.name AS "Name", s.state_id::text AS "Code"
        FROM config.states s
        JOIN config.countries c ON c.country_id = s.country_id
        WHERE s.is_active
          AND s.country_id = COALESCE(v_parent, (SELECT country_id FROM config.countries WHERE iso2 = 'IN'))
        ORDER BY s.display_order, s.name;

    ELSIF p_activity = 'District' THEN

        IF v_parent IS NULL THEN
            RAISE EXCEPTION 'State id is required to list districts.';
        END IF;

        OPEN p_result FOR
        SELECT name AS "Name", district_id::text AS "Code"
        FROM config.districts
        WHERE is_active AND state_id = v_parent
        ORDER BY name;

    ELSE
        RAISE EXCEPTION 'Unknown geo activity: %', p_activity;
    END IF;
END;
$procedure$;

