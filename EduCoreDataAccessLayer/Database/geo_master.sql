-- ============================================================================
-- GEOGRAPHY MASTER — Country / State / District
--
-- WHY: address "State" and "City" are free-text boxes on every form in the app.
-- core.school_addresses already holds 'UP', 'uttarpradesh', 'Uttar Pradesh',
-- 'delhi', 'Haryana', 'Haryanafff' and 'TEST' for what is really four states,
-- which breaks the state filter on the school list and every state-wise report.
--
-- DESIGN
--   * NOT tenant-scoped. "Maharashtra" is the same for every tenant, so these
--     tables deliberately have no tenant_id / school_id (unlike config.roles or
--     config.boards). Platform-owned reference data, same class as
--     config.date_formats. This is also why GeoService caches on a GLOBAL key
--     instead of AppCache.Key(name, tenantId, schoolId) — do not "fix" that.
--   * Hierarchical, so it does NOT live in config.lookup_value: that table is
--     flat (category/code/label) with no parent link.
--   * District, not city. India has ~4,000 towns but ~800 districts; district is
--     the unit CBSE / state-board / TC forms actually ask for, and the list stays
--     small enough to keep current. City remains free text with district-driven
--     suggestions.
--
-- MAINTENANCE: states create and rename districts (Rajasthan 2023, Assam 2022,
-- AP 2022...). These lists are a starting point, not gospel — they are plain
-- rows and can be INSERTed/renamed without a code change. Re-runnable:
-- every seed is ON CONFLICT DO NOTHING.
-- ============================================================================

-- ── Tables ─────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS config.countries (
    country_id    integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iso2          char(2)      NOT NULL,
    name          varchar(100) NOT NULL,
    phone_code    varchar(8),
    display_order integer      NOT NULL DEFAULT 0,
    is_active     boolean      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_country_iso2 UNIQUE (iso2)
);

CREATE TABLE IF NOT EXISTS config.states (
    state_id           integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id         integer      NOT NULL REFERENCES config.countries(country_id),
    state_code         varchar(10)  NOT NULL,   -- ISO 3166-2 subdivision code (MH, UP, DL...)
    name               varchar(100) NOT NULL,
    is_union_territory boolean      NOT NULL DEFAULT FALSE,
    display_order      integer      NOT NULL DEFAULT 0,
    is_active          boolean      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_state_code UNIQUE (country_id, state_code)
);

CREATE TABLE IF NOT EXISTS config.districts (
    district_id integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state_id    integer      NOT NULL REFERENCES config.states(state_id),
    name        varchar(120) NOT NULL,
    is_active   boolean      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_district_name UNIQUE (state_id, name)
);

CREATE INDEX IF NOT EXISTS ix_states_country   ON config.states (country_id)  WHERE is_active;
CREATE INDEX IF NOT EXISTS ix_districts_state  ON config.districts (state_id) WHERE is_active;

