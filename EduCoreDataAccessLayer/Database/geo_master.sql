ALTER TABLE core.school_addresses
    ADD COLUMN IF NOT EXISTS country_id  integer REFERENCES config.countries(country_id),
    ADD COLUMN IF NOT EXISTS state_id    integer REFERENCES config.states(state_id),
    ADD COLUMN IF NOT EXISTS district_id integer REFERENCES config.districts(district_id);

-- Backfill the rows whose free text maps cleanly onto a real state. Anything
-- that does not match is left with a NULL state_id and its original text, so it
-- shows up in the "needs cleanup" query below rather than being silently lost.
UPDATE core.school_addresses a
SET state_id   = s.state_id,
    country_id = s.country_id
FROM config.states s
WHERE a.state_id IS NULL
  AND LOWER(TRIM(a.state)) = LOWER(s.name);

UPDATE core.school_addresses a
SET district_id = d.district_id
FROM config.districts d
WHERE a.district_id IS NULL
  AND a.state_id = d.state_id
  AND LOWER(TRIM(COALESCE(a.district, ''))) = LOWER(d.name);

